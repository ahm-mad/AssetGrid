-- ============================================================================
-- RLS — `marina` scope on the denormalised marina_id; writes need marina perm.
-- contract_sign_tokens: no policy (service-role only — the sign route uses it).
-- ============================================================================
do $$
declare t text;
begin
  foreach t in array array[
    'rate_plans','reservations','quotes','contracts','contract_amendments',
    'assignments','stays','pos_transactions','invoices','ledgers','meters'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format($f$
      create policy %1$I_select on public.%1$I for select to authenticated
      using (
        public.auth_is_super_admin()
        or (marina_id is null and public.auth_can('marina','read'))
        or (marina_id is not null and public.auth_can('marina','read')
            and public.auth_scope_allows('marina', marina_id))
      );
      create policy %1$I_write on public.%1$I for all to authenticated
      using (public.auth_can('marina','update'))
      with check (public.auth_can('marina','create'));
    $f$, t);
  end loop;
end $$;

alter table public.contract_sign_tokens enable row level security;
-- (no policies — only the service-role client touches it)
