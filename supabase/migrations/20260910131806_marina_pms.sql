-- ============================================================================
-- Slice 8: Marina PMS chain
-- Source: docs/backend/domains/marina.md §B, docs/target/schema-postgres.md §11
--   "Marina PMS chain", live ddev SHOW CREATE TABLE, PricingService.
-- ADRs: 024 (pos_sales + pos_transactions merged), 026 (money numeric(12,2)).
--
-- Money is DOLLARS (confirmed from PricingService — decimal + round(x,2),
-- TAX_RATE 0.08). The old int(11) columns in quotes/reservations become
-- numeric(12,2). `discount_type` is a code ('percent'|'fixed'), modelled text.
-- Every PMS table carries a denormalised `marina_id` for the one-hop
-- `marina`-scope RLS (same pattern as slices 6/7).
-- ============================================================================

-- ----------------------------------------------------------------------------
-- rate_plans  (+ the deferred slips.rate_plan_id FK from slice 7)
-- ----------------------------------------------------------------------------
create table public.rate_plans (
  id         bigint generated by default as identity primary key,
  name       text,
  calc_type  text,                       -- 'monthly' | 'nightly' | …
  rate       numeric(12,2),
  start_date date,
  end_date   date,
  type       public.rate_plan_type,      -- 'percent' | 'fixed'
  condition  jsonb,                       -- [{ loa_operator, loa_value_1, loa_value_2 }]
  loa_unit   text,
  value      numeric(12,4),
  marina_id  bigint not null references public.marinas(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index rate_plans_marina_idx on public.rate_plans (marina_id);
create trigger rate_plans_set_updated_at before update on public.rate_plans
  for each row execute function public.set_updated_at();

alter table public.slips
  add constraint slips_rate_plan_id_fkey
  foreign key (rate_plan_id) references public.rate_plans(id) on delete set null;

-- ----------------------------------------------------------------------------
-- reservations  (referenced by quotes.reservation_id — created first)
-- ----------------------------------------------------------------------------
create table public.reservations (
  id           bigint generated by default as identity primary key,
  xnid         text,
  marina_id    bigint references public.marinas(id) on delete cascade,
  user_id      uuid   references public.profiles(id) on delete set null,
  dock_id      bigint references public.docks(id) on delete set null,
  boat_id      bigint references public.boats(id) on delete set null,
