  slip_id              bigint not null references public.slips(id) on delete cascade,
  boat_id              bigint not null references public.boats(id) on delete cascade,
  rate_plan_id         bigint not null references public.rate_plans(id) on delete cascade,
  reservation_id       bigint references public.reservations(id) on delete set null,
  contract_type        text,
  monthly_rate         numeric(12,2) not null,
  status               public.contract_status not null default 'required',
  signed_at            timestamptz,
  original_contract_id bigint references public.contracts(id) on delete set null,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create index contracts_marina_idx on public.contracts (marina_id);
create index contracts_slip_idx on public.contracts (slip_id);
create index contracts_boat_idx on public.contracts (boat_id);
create index contracts_status_idx on public.contracts (status);
create trigger contracts_set_updated_at before update on public.contracts
  for each row execute function public.set_updated_at();

create table public.contract_amendments (
  id                  bigint generated by default as identity primary key,
  xnid                text,
  marina_id           bigint references public.marinas(id) on delete cascade,
  contract_id         bigint not null references public.contracts(id) on delete cascade,
  amendment_type      text not null,          -- rate_change | date_extension | slip_change | terms_change
  description         text,
  changed_fields      jsonb,
  original_amount     numeric(12,2),
  new_amount          numeric(12,2),
  original_start_date date,
  original_end_date   date,
  new_start_date      date,
  new_end_date        date,
  original_slip_id    bigint references public.slips(id) on delete set null,
  new_slip_id         bigint references public.slips(id) on delete set null,
  status              text not null default 'draft',
  signed_at           timestamptz,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);
create index contract_amendments_contract_idx on public.contract_amendments (contract_id);
create trigger contract_amendments_set_updated_at before update on public.contract_amendments
  for each row execute function public.set_updated_at();

-- Contract e-signature tokens (public signed-URL flow, replaces Laravel `signed`).
create table public.contract_sign_tokens (
  token       text primary key,
  contract_id bigint not null references public.contracts(id) on delete cascade,
  amendment_id bigint references public.contract_amendments(id) on delete cascade,
  expires_at  timestamptz not null,
  used_at     timestamptz,
  created_at  timestamptz not null default now()
);
create index contract_sign_tokens_contract_idx on public.contract_sign_tokens (contract_id);

