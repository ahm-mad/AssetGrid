-- ----------------------------------------------------------------------------
-- alert_state  (replaces xup_notification_info + the dead device_states shape)
-- one row per (user_device, attribute) — the alert/safeguard state machine.
-- ----------------------------------------------------------------------------
create table public.alert_state (
  id                    bigint generated by default as identity primary key,
  user_device_id        bigint not null references public.user_devices(id) on delete cascade,
  attribute_id          bigint references public.attributes(id) on delete cascade,
  dev_eui               text not null,
  product_id            bigint references public.products(id) on delete set null,
  notifie_id            bigint references public.notifies(id) on delete set null,
  inventory_device_id   bigint references public.inventory_devices(id) on delete cascade,

  value                 numeric,
  prev_value            numeric,
  is_alert              boolean not null default false,
  notification          text,               -- the xup data_type ("temperature", …)
  notification_type     text not null default 'normal',   -- 'normal' | 'alert'
  admin_bypass          boolean not null default false,   -- old active_status = 1

  alerts_count_24h      int not null default 0,
  window_started_at     timestamptz,
  last_alert_at         timestamptz,
  paused_until          timestamptz,
  notifications_paused  boolean not null default false,
  support_email_sent_at timestamptz,

  triggering_reading_id bigint,             -- telemetry(id); not FK across partitions
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  unique (user_device_id, attribute_id)
);
create index alert_state_deveui_idx on public.alert_state (dev_eui);
create index alert_state_inventory_idx on public.alert_state (inventory_device_id);
create trigger alert_state_set_updated_at before update on public.alert_state
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- alert_rules  (was customer_notifie_rules — the customer Rule Builder)
-- ----------------------------------------------------------------------------
create table public.alert_rules (
  id         bigint generated by default as identity primary key,
  title      text,
  is_active  boolean not null default true,      -- was `status`
  user_id    uuid not null references public.profiles(id) on delete cascade,
  devices    jsonb,        -- [{ product_id, user_device_id, inventory_device_id }]
  conditions jsonb,        -- [{ selectedAttribute, selectedCondition, conditionValue, logicalOperator }]
  notifie    text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index alert_rules_user_idx on public.alert_rules (user_id);
create trigger alert_rules_set_updated_at before update on public.alert_rules
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- alert_windows  (was notification_schedulers — quiet-hours / active-window)
-- building_id / marina_id stay plain bigint here; the FKs are added when the
-- buildings (slice 6) and marinas (slice 7) tables exist.
-- ----------------------------------------------------------------------------
create table public.alert_windows (
  id            bigint generated by default as identity primary key,
  rule_name     text,
  building_id   bigint,
  marina_id     bigint,
  company_id    bigint references public.companies(id) on delete set null,   -- was varchar (B10)
  attribute_key text not null,
  inventories   jsonb,      -- [{ value, label }] — inventory_device ids as strings
  days          text[],
  recurrence    public.scheduler_recurrence not null default 'weekly',
  start_time    time not null,
  end_time      time not null,
  timezone      text not null default 'UTC',
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);
create index alert_windows_attr_idx on public.alert_windows (attribute_key);
create trigger alert_windows_set_updated_at before update on public.alert_windows
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- notification_prefs  (was notifications — channel-config toggles)
-- ----------------------------------------------------------------------------
create table public.notification_prefs (
