alter table public.alert_state                    enable row level security;
alter table public.alert_rules                     enable row level security;
alter table public.alert_windows                   enable row level security;
alter table public.notification_prefs              enable row level security;
alter table public.device_notification_recipients  enable row level security;
alter table public.alert_log                       enable row level security;

-- alert_state: readable by the device owner or an inventory reader; writes via service role
create policy alert_state_select on public.alert_state for select to authenticated
  using (
    public.auth_is_super_admin()
    or public.auth_can('inventory', 'read')
    or public.auth_owns_user_device(user_device_id)
  );

-- alert_rules: a user owns their own rules; rulebuilder perm sees all
create policy alert_rules_select on public.alert_rules for select to authenticated
  using (user_id = auth.uid() or public.auth_can('rulebuilder', 'read'));
create policy alert_rules_write on public.alert_rules for all to authenticated
  using (user_id = auth.uid() or public.auth_can('rulebuilder', 'update'))
  with check (user_id = auth.uid() or public.auth_can('rulebuilder', 'create'));

-- alert_windows: rulebuilder module
create policy alert_windows_select on public.alert_windows for select to authenticated
  using (public.auth_can('rulebuilder', 'read'));
create policy alert_windows_write on public.alert_windows for all to authenticated
  using (public.auth_can('rulebuilder', 'update'))
  with check (public.auth_can('rulebuilder', 'create'));

-- notification_prefs: own rows, or messaging perm
create policy notification_prefs_all on public.notification_prefs for all to authenticated
  using (user_id = auth.uid() or public.auth_can('messaging', 'update'))
  with check (user_id = auth.uid() or public.auth_can('messaging', 'create'));

-- device_notification_recipients: own device, or inventory/messaging perm
create policy device_notification_recipients_all on public.device_notification_recipients for all to authenticated
  using (
    user_id = auth.uid()
    or (user_device_id is not null and public.auth_owns_user_device(user_device_id))
    or public.auth_can('inventory', 'update')
    or public.auth_can('messaging', 'update')
  )
  with check (
    user_id = auth.uid()
    or (user_device_id is not null and public.auth_owns_user_device(user_device_id))
    or public.auth_can('inventory', 'update')
    or public.auth_can('messaging', 'update')
  );

-- alert_log: own rows, or messaging read; writes via service role
create policy alert_log_select on public.alert_log for select to authenticated
  using (user_id = auth.uid() or public.auth_can('messaging', 'read') or public.auth_is_super_admin());

