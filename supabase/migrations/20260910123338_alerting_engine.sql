  user_device_id bigint references public.user_devices(id) on delete cascade,
  company_id     bigint references public.companies(id) on delete cascade,

  email_enabled            boolean not null default false,
  phone_enabled            boolean not null default false,
  customer_phone_enabled   boolean not null default false,
  customer_email_enabled   boolean not null default false,
  manager_phone_enabled    boolean not null default false,
  manager_email_enabled    boolean not null default false,
  device_phone_enabled     boolean not null default false,
  device_email_enabled     boolean not null default false,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index notification_prefs_user_idx on public.notification_prefs (user_id);
create index notification_prefs_user_device_idx on public.notification_prefs (user_device_id);
create trigger notification_prefs_set_updated_at before update on public.notification_prefs
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- device_notification_recipients  (was notification_addresses — merged, arrays)
-- ----------------------------------------------------------------------------
create table public.device_notification_recipients (
  id             bigint generated by default as identity primary key,
  user_id        uuid   references public.profiles(id) on delete cascade,
  user_device_id bigint references public.user_devices(id) on delete cascade,
  emails         text[] not null default '{}',
  phone_numbers  text[] not null default '{}',
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now(),
  unique (user_device_id)
);
create trigger device_notification_recipients_set_updated_at before update on public.device_notification_recipients
  for each row execute function public.set_updated_at();

-- ----------------------------------------------------------------------------
-- alert_log  (was notification_logs — audit of every alert email / SMS sent)
-- ----------------------------------------------------------------------------
create table public.alert_log (
  id             bigint generated by default as identity primary key,
  user_id        uuid   references public.profiles(id) on delete set null,
  telemetry_id   bigint,                     -- was device_value_id varchar
  device_name    text,
  user_device_id bigint references public.user_devices(id) on delete set null,
  channel        public.notification_channel not null,   -- was `type`
  recipient      text not null,
  message        text not null,
  subject        text,
  created_at     timestamptz not null default now()
);
create index alert_log_user_idx on public.alert_log (user_id);
create index alert_log_user_device_idx on public.alert_log (user_device_id);
create index alert_log_created_idx on public.alert_log (created_at);

