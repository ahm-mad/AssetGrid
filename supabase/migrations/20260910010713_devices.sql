-- user_devices: the implicit per-role ownership
create policy user_devices_select on public.user_devices for select to authenticated
  using (public.auth_owns_user_device(id));
create policy user_devices_write on public.user_devices for all to authenticated
  using (public.auth_owns_user_device(id))
  with check (
    user_id = auth.uid()
    or public.auth_can('inventory', 'update')
    or public.auth_is_super_admin()
  );

-- per-device config/state tables: gated by owning the user_device (or inventory perm)
do $$
declare t text;
begin
  foreach t in array array[
    'device_parameters','device_schedules','sunset_rises','charging_timers',
    'device_charging_state','energy_usage_sessions','safeguard_configurations'
  ]
  loop
    execute format($f$
      create policy %1$I on public.%2$I for all to authenticated
      using (
        public.auth_is_super_admin()
        or public.auth_can('inventory','update')
        or (%2$I.user_device_id is not null and public.auth_owns_user_device(%2$I.user_device_id))
      )
      with check (
        public.auth_is_super_admin()
        or public.auth_can('inventory','update')
        or (%2$I.user_device_id is not null and public.auth_owns_user_device(%2$I.user_device_id))
      )
    $f$, t || '_all', t);
  end loop;
end $$;

