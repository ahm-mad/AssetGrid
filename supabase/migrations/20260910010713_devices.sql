-- containers: readable by anyone with inventory access; writes with inventory
create policy containers_select on public.containers for select to authenticated
  using (public.auth_can('inventory', 'read') or public.auth_is_customer());
create policy containers_write on public.containers for all to authenticated
  using (public.auth_can('inventory', 'update')) with check (public.auth_can('inventory', 'create'));

-- inventory_devices: inventory scope + auth_scope_allows('inventory', id)
create policy inventory_devices_select on public.inventory_devices for select to authenticated
  using (
    public.auth_is_super_admin()
    or (public.auth_can('inventory', 'read') and public.auth_scope_allows('inventory', id))
    or (public.auth_is_customer() and exists (
          select 1 from public.user_devices ud
          where ud.inventory_device_id = inventory_devices.id
            and public.auth_owns_user_device(ud.id)))
  );
create policy inventory_devices_write on public.inventory_devices for all to authenticated
  using (public.auth_can('inventory', 'update') and public.auth_scope_allows('inventory', id))
  with check (public.auth_can('inventory', 'create'));

-- inventory_device_secrets: Super Admin or Admin-with-inventory-write only (A10 / ADR-025)
create policy inventory_device_secrets_select on public.inventory_device_secrets for select to authenticated
  using (
    public.auth_is_super_admin()
    or (public.auth_role_title() = 'Admin' and public.auth_can('inventory', 'update'))
  );
create policy inventory_device_secrets_write on public.inventory_device_secrets for all to authenticated
  using (public.auth_is_super_admin() or (public.auth_role_title() = 'Admin' and public.auth_can('inventory', 'update')))
  with check (public.auth_is_super_admin() or (public.auth_role_title() = 'Admin' and public.auth_can('inventory', 'update')));

-- subscription_entitlements: commerce read; writes via service role (Stripe/provisioning)
