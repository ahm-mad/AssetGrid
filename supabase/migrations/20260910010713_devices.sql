-- ============================================================================
-- auth_owns_user_device()  (auth-design.md §4 — the implicit per-role device
-- ownership from the old userLogin logic). Referenced by RLS on the device
-- tables and later `telemetry` / `alert_state`.
-- ============================================================================
create or replace function public.auth_owns_user_device(p_user_device bigint, p_user uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  with me as (
    select p.id, p.company_id, rt.title as role,
           coalesce(d.container_codes, '{}'::text[]) as container_codes,
           coalesce(d.inventory_device_ids, '{}'::bigint[]) as inventory_device_ids
    from public.profiles p
    join public.role_types rt on rt.id = p.role_type_id
    left join public.profile_details d on d.user_id = p.id
    where p.id = p_user
  ),
  ud as (
    select ud.user_id, ud.inventory_device_id, c.code as container_code
    from public.user_devices ud
    left join public.inventory_devices idv on idv.id = ud.inventory_device_id
    left join public.containers c on c.id = idv.container_id
    where ud.id = p_user_device
  )
  select case (select role from me)
    when 'Super Admin' then true
    when 'Customer'    then exists (select 1 from ud u where u.user_id = p_user)
    when 'Manager' then exists (
      select 1 from me m, ud u
      join public.profiles o on o.id = u.user_id
      where m.company_id is not null and o.company_id = m.company_id)
    when 'Admin' then exists (
      select 1 from me m, ud u
      join public.profiles o on o.id = u.user_id
      where m.company_id is not null and o.company_id = m.company_id)
    when 'Dealer' then exists (
      select 1 from me m, ud u
      where u.container_code = any (m.container_codes))
    when 'Partner' then exists (
      select 1 from me m, ud u
      where u.inventory_device_id = any (m.inventory_device_ids))
    else false
  end;
$$;

